import Foundation
import XCTest
@testable import BridgeyMac

final class AutoClipboardTests: XCTestCase {
    private let plain = ["public.utf8-plain-text"]

    private func snapshot(_ text: String?, count: Int = 1, types: [String]? = nil, html: String? = nil) -> ClipboardSnapshot {
        ClipboardSnapshot(changeCount: count, types: types ?? (text == nil ? [] : plain), text: text, html: html)
    }

    // MARK: Skip rules

    func testSendsPlainAndRichText() {
        var filter = AutoClipboardFilter()
        XCTAssertEqual(filter.decide(snapshot("Room 2 at 4")), .send(text: "Room 2 at 4", html: nil))
        XCTAssertEqual(filter.decide(snapshot("<b>Bold</b> text", count: 2, html: "<b>Bold</b>")), .send(text: "<b>Bold</b> text", html: "<b>Bold</b>"))
    }

    func testSkipsConcealedTransientAndGeneratedContent() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            var filter = AutoClipboardFilter()
            XCTAssertEqual(filter.decide(snapshot("hunter2", types: plain + [marker])), .skip(.secret), marker)
        }
    }

    func testSkipsEmptyAndNonTextContent() {
        var filter = AutoClipboardFilter()
        XCTAssertEqual(filter.decide(snapshot(nil)), .skip(.empty))
        XCTAssertEqual(filter.decide(snapshot("", count: 2)), .skip(.empty))
        XCTAssertEqual(filter.decide(snapshot(" \n\t", count: 3)), .skip(.empty))
        XCTAssertEqual(filter.decide(snapshot(nil, count: 4, types: ["public.png"])), .skip(.notText))
    }

    func testSkipsContentOverTheClipboardLimit() {
        var filter = AutoClipboardFilter()
        let limit = String(repeating: "a", count: maximumClipboardContentBytes)
        XCTAssertEqual(filter.decide(snapshot(limit + "b")), .skip(.tooLarge))
        XCTAssertEqual(filter.decide(snapshot(limit, count: 2)), .send(text: limit, html: nil))
        // Multibyte text counts bytes, not characters.
        let wide = String(repeating: "\u{0416}", count: maximumClipboardContentBytes / 2 + 1)
        XCTAssertEqual(filter.decide(snapshot(wide, count: 3)), .skip(.tooLarge))
    }

    // MARK: Loop prevention

    func testIdenticalContentIsNotSentTwice() {
        var filter = AutoClipboardFilter()
        XCTAssertEqual(filter.decide(snapshot("same", count: 1)), .send(text: "same", html: nil))
        XCTAssertEqual(filter.decide(snapshot("same", count: 2)), .skip(.duplicate))
        XCTAssertEqual(filter.decide(snapshot("other", count: 3)), .send(text: "other", html: nil))
        XCTAssertEqual(filter.decide(snapshot("same", count: 4)), .send(text: "same", html: nil), "only the last clip counts as a duplicate")
    }

    func testClipSentByHandIsNotSentAgain() {
        var filter = AutoClipboardFilter()
        filter.noteSent(text: "by hand")
        XCTAssertEqual(filter.decide(snapshot("by hand", count: 5)), .skip(.duplicate))
    }

    func testReceivedClipNeverBouncesBack() {
        var filter = AutoClipboardFilter()
        filter.noteReceived(text: "from the phone", changeCount: 7)
        // The pasteboard change Bridgey made itself.
        XCTAssertEqual(filter.decide(snapshot("from the phone", count: 7)), .skip(.ownWrite))
        // Even if another app re-copies the same text, it is the phone's own clip.
        XCTAssertEqual(filter.decide(snapshot("from the phone", count: 8)), .skip(.duplicate))
        // A new copy on the Mac goes out.
        XCTAssertEqual(filter.decide(snapshot("typed on the Mac", count: 9)), .send(text: "typed on the Mac", html: nil))
    }

    func testOwnWriteWinsOverOtherRules() {
        var filter = AutoClipboardFilter()
        filter.noteReceived(text: "x", changeCount: 3)
        XCTAssertEqual(filter.decide(snapshot("y", count: 3, types: plain + ["org.nspasteboard.ConcealedType"])), .skip(.ownWrite))
    }

    // MARK: Debounce

    func testChangeIsProcessedOnceAfterThreeHundredMilliseconds() {
        let start = Date(timeIntervalSince1970: 100)
        var debouncer = ClipboardChangeDebouncer(changeCount: 10)
        XCTAssertNil(debouncer.poll(changeCount: 10, now: start), "what is already on the clipboard is never sent")
        XCTAssertNil(debouncer.poll(changeCount: 11, now: start))
        XCTAssertEqual(debouncer.nextDeadline, start.addingTimeInterval(0.3))
        XCTAssertNil(debouncer.poll(changeCount: 11, now: start.addingTimeInterval(0.29)))
        XCTAssertEqual(debouncer.poll(changeCount: 11, now: start.addingTimeInterval(0.3)), 11)
        XCTAssertNil(debouncer.poll(changeCount: 11, now: start.addingTimeInterval(0.8)), "processed only once")
        XCTAssertNil(debouncer.nextDeadline)
    }

    func testBurstOfCopiesSendsOnlyTheLast() {
        let start = Date(timeIntervalSince1970: 100)
        var debouncer = ClipboardChangeDebouncer(changeCount: 1)
        XCTAssertNil(debouncer.poll(changeCount: 2, now: start))
        XCTAssertNil(debouncer.poll(changeCount: 3, now: start.addingTimeInterval(0.2)))
        XCTAssertNil(debouncer.poll(changeCount: 4, now: start.addingTimeInterval(0.4)))
        XCTAssertNil(debouncer.poll(changeCount: 4, now: start.addingTimeInterval(0.6)))
        XCTAssertEqual(debouncer.poll(changeCount: 4, now: start.addingTimeInterval(0.7)), 4)
    }

    // MARK: Settings

    func testDeviceSwitchFollowsTheGlobalSwitchUntilChanged() {
        var model = SettingsModel()
        model.autoClipboard = true
        XCTAssertTrue(model.isAutoClipboardEnabled(for: "phone"))
        model.autoClipboardDevices["phone"] = false
        XCTAssertFalse(model.isAutoClipboardEnabled(for: "phone"))
        XCTAssertTrue(model.isAutoClipboardEnabled(for: "tablet"))
        model.autoClipboard = false
        model.autoClipboardDevices["tablet"] = true
        XCTAssertFalse(model.isAutoClipboardEnabled(for: "tablet"), "the global switch wins")
    }

    func testActivityMarksAutomaticClipboardItems() {
        let items = ActivityHistory.add([], kind: .clipboardSent, deviceID: "d", deviceName: "Phone", preview: "Hi",
                                        automatic: true, now: Date(), nextID: 1)
        XCTAssertTrue(items[0].automatic)
        XCTAssertEqual(ActivityText.detail(items[0], showPreviews: true), "Automatic \u{00B7} \u{201C}Hi\u{201D}")
        XCTAssertEqual(ActivityText.detail(items[0], showPreviews: false), "Automatic")
        let ping = ActivityHistory.add([], kind: .pingSent, deviceID: "d", deviceName: "Phone", automatic: true, now: Date(), nextID: 1)
        XCTAssertFalse(ping[0].automatic, "only clipboard items can be automatic")
    }
}
