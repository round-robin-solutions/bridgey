import AppKit
import CryptoKit
import Foundation

/*
 * Automatic clipboard, Mac side: copy on one device, paste on the other. No protocol change:
 * changes go out through the existing clipboard.update / clipboard.rich messages, so it also
 * works with upstream peers. The rules are pure and unit tested; the watcher only polls the
 * pasteboard while it is active (connected, clipboard available on both sides, switch on).
 */

/// Content that is secret or short-lived; Automatic clipboard never sends it.
let skippedClipboardTypes: Set<String> = secretClipboardTypes.union([
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
])

struct ClipboardSnapshot: Equatable {
    var changeCount: Int
    var types: [String]
    var text: String?
    var html: String?
}

enum AutoClipboardSkip: Equatable {
    /// Bridgey wrote this clip itself (it came from the phone).
    case ownWrite
    /// A password manager or another app marked it concealed, transient or generated.
    case secret
    case empty
    case notText
    /// Over the 32 KiB clipboard limit; the user gets one quiet status, no retry.
    case tooLarge
    /// Same text as the last clip sent or received.
    case duplicate
}

enum AutoClipboardDecision: Equatable {
    case send(text: String, html: String?)
    case skip(AutoClipboardSkip)
}

/// Decides whether a pasteboard change goes to the phone. Loop prevention: the change count of a
/// clip Bridgey wrote, plus a hash of the last text sent or received.
struct AutoClipboardFilter {
    private(set) var lastContentHash: String?
    private(set) var ownChangeCount: Int?

    mutating func decide(_ snapshot: ClipboardSnapshot) -> AutoClipboardDecision {
        if let ownChangeCount, snapshot.changeCount == ownChangeCount { return .skip(.ownWrite) }
        if snapshot.types.contains(where: skippedClipboardTypes.contains) { return .skip(.secret) }
        guard let text = snapshot.text else { return .skip(snapshot.types.isEmpty ? .empty : .notText) }
        if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .skip(.empty) }
        guard clipboardTextFits(text) else { return .skip(.tooLarge) }
        let hash = Self.hash(text)
        if hash == lastContentHash { return .skip(.duplicate) }
        lastContentHash = hash
        return .send(text: text, html: snapshot.html)
    }

    /// A clip sent by hand: Automatic clipboard must not send it again.
    mutating func noteSent(text: String) {
        lastContentHash = Self.hash(text)
    }

    /// A clip from the phone, written to the pasteboard at `changeCount`: never bounce it back.
    mutating func noteReceived(text: String, changeCount: Int) {
        lastContentHash = Self.hash(text)
        ownChangeCount = changeCount
    }

    static func hash(_ text: String) -> String {
        SHA256.hash(data: Data(text.utf8)).map { String(format: "%02x", $0) }.joined()
    }
}

/// Waits until the pasteboard has been still for `delay` before a change is processed, so a
/// burst of copies sends only the last one.
struct ClipboardChangeDebouncer {
    let delay: TimeInterval
    private(set) var lastSeen: Int
    private(set) var pending: (changeCount: Int, due: Date)?

    init(changeCount: Int, delay: TimeInterval = 0.3) {
        lastSeen = changeCount
        self.delay = delay
    }

    /// Call on every poll. Returns the change count to process once a change has settled.
    mutating func poll(changeCount: Int, now: Date) -> Int? {
        if changeCount != lastSeen {
            lastSeen = changeCount
            pending = (changeCount, now.addingTimeInterval(delay))
            return nil
        }
        if let pending, now >= pending.due {
            self.pending = nil
            return pending.changeCount
        }
        return nil
    }

    var nextDeadline: Date? { pending?.due }
}

/// Polls `NSPasteboard.general.changeCount` about every 0.5 s while active; stopped otherwise.
@MainActor
final class AutoClipboardWatcher {
    static let pollInterval: TimeInterval = 0.5

    var onSend: (_ text: String, _ html: String?) -> Void = { _, _ in }
    var onTooLarge: () -> Void = {}

    private let pasteboard: NSPasteboard
    private var filter = AutoClipboardFilter()
    private var debouncer: ClipboardChangeDebouncer?
    private var timer: Timer?
    private var settleWork: DispatchWorkItem?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var isActive: Bool { timer != nil }

    /// Starting ignores what is already on the clipboard; only new copies are sent.
    func setActive(_ active: Bool) {
        guard active != isActive else { return }
        if active {
            debouncer = ClipboardChangeDebouncer(changeCount: pasteboard.changeCount)
            let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
                Task { @MainActor [weak self] in self?.tick() }
            }
            timer.tolerance = 0.1
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else {
            timer?.invalidate()
            timer = nil
            settleWork?.cancel()
            settleWork = nil
            debouncer = nil
        }
    }

    func noteSent(text: String) {
        filter.noteSent(text: text)
    }

    func noteReceived(text: String, changeCount: Int) {
        filter.noteReceived(text: text, changeCount: changeCount)
    }

    private func tick() {
        guard var debouncer else { return }
        let ready = debouncer.poll(changeCount: pasteboard.changeCount, now: Date())
        self.debouncer = debouncer
        if let ready {
            process(ready)
        } else if let due = debouncer.nextDeadline, settleWork == nil {
            // Check again exactly when the change settles instead of waiting for the next poll.
            let work = DispatchWorkItem { [weak self] in
                self?.settleWork = nil
                self?.tick()
            }
            settleWork = work
            DispatchQueue.main.asyncAfter(deadline: .now() + max(due.timeIntervalSinceNow, 0), execute: work)
        }
    }

    private func process(_ changeCount: Int) {
        // Changed again since it settled: the next poll picks up the newer clip.
        guard pasteboard.changeCount == changeCount else { return }
        let snapshot = ClipboardSnapshot(
            changeCount: changeCount,
            types: (pasteboard.types ?? []).map(\.rawValue),
            text: pasteboard.string(forType: .string),
            html: pasteboard.data(forType: .html).flatMap { String(data: $0, encoding: .utf8) }
        )
        switch filter.decide(snapshot) {
        case let .send(text, html): onSend(text, html)
        case .skip(.tooLarge): onTooLarge()
        case .skip: break
        }
    }
}
