//! Golden vectors for Connect anywhere (`protocol/test-vectors/connect-v1.json`). Rust is the
//! source; Android, macOS and Python check their own derivations against the same file.

use crate::{b64, derive, rdv, seal};
use serde_json::{json, Value};

pub const C_LOW: [u8; 32] = seq(0x01);
pub const C_HIGH: [u8; 32] = seq(0x21);
pub const ID_LOW: &str = "1a2b3c4d-0000-4000-8000-000000000001";
pub const ID_HIGH: &str = "9f8e7d6c-0000-4000-8000-000000000002";

const fn seq(start: u8) -> [u8; 32] {
    let mut out = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        out[i] = start + i as u8;
        i += 1;
    }
    out
}

/// The tunnel transcript (spec 5.3); `bridgey-auth-v1` stays on TCP.
pub fn transcript_v2(session_id: &str, initiator: &str, responder: &str, initiator_key: &str, responder_key: &str, exporter_b64: &str) -> Vec<u8> {
    ["bridgey-auth-v2", session_id, initiator, responder, initiator_key, responder_key, exporter_b64].join("\0").into_bytes()
}

pub fn generate() -> Value {
    let secret = derive::pair_secret(&C_LOW, &C_HIGH, ID_LOW, ID_HIGH);
    let sig_key = derive::sig_key(&secret);
    let dates = ["2026-10-27", "2026-10-28"];
    let rdv_ids: serde_json::Map<String, Value> = dates.iter().map(|d| (d.to_string(), json!(derive::rdv_id(&secret, d)))).collect();
    let exporter = b64::std_encode(&seq(0x41));
    let transcript = transcript_v2(
        "4f1c2a9e-6b3d-4c8e-9a1f-2d3e4f5a6b7c",
        ID_LOW,
        ID_HIGH,
        "BOk3Q2xvd3IHN0YWJsZS1lcGhlbWVyYWwta2V5LWluaXRpYXRvcg==",
        "BOk3Q2xvd3IHN0YWJsZS1lcGhlbWVyYWwta2V5LXJlc3BvbmRlcg==",
        &exporter,
    );
    let sid = "q7Lw0d3xV2c9kP1sR8uT4w";
    let rdv_today = derive::rdv_id(&secret, dates[0]);
    let plaintext = r#"{"t":"bye","sid":"q7Lw0d3xV2c9kP1sR8uT4w","reason":"done","ts":1793103650000,"seq":3}"#;
    let mut nonce = [0u8; 12];
    nonce.copy_from_slice(&seq(0x61)[..12]);
    let body = seal::seal_with_nonce(&sig_key, &rdv_today, 0, sid, plaintext.as_bytes(), nonce);
    let auth_nonce = seq(0x81);
    let mut node = vec![4u8];
    node.extend_from_slice(&seq(0x10));
    node.extend_from_slice(&seq(0x30));
    let (username, credential) = rdv::turn_rest_credentials(b"test-secret", 1_761_407_200, sid, 0);
    json!({
        "description": "Connect anywhere golden vectors (docs/connect-anywhere.md, docs/protocol.md 'Draft: Connect anywhere'). Generated by `cargo run -p bridgey-connect-proto --example vectors` in rust/; checked by the Rust, Android (ConnectVectorsTest), macOS (ConnectVectorsTests) and Python (scripts/rr/tests/test_connect_vectors.py) suites. Base64 is standard with padding unless the field ends in Url (URL-safe, no padding). cLow is the 32-byte contribution of the lower device ID (plain string order).",
        "pair": {
            "cLow": b64::std_encode(&C_LOW),
            "cHigh": b64::std_encode(&C_HIGH),
            "idLow": ID_LOW,
            "idHigh": ID_HIGH,
            "pairSecret": b64::std_encode(&secret),
            "pairCheckUrl": derive::pair_check(&secret),
            "sigKey": b64::std_encode(&sig_key),
            "rdvIdsUrl": rdv_ids,
            "netTagUrl": {"fingerprint": "gw=192.168.1.1;dns=192.168.1.1;v6=2409:4040:1:2::/64;t=wifi", "tag": derive::net_tag(&secret, b"gw=192.168.1.1;dns=192.168.1.1;v6=2409:4040:1:2::/64;t=wifi")},
        },
        "transcript": {
            "sessionId": "4f1c2a9e-6b3d-4c8e-9a1f-2d3e4f5a6b7c",
            "initiatorDeviceId": ID_LOW,
            "responderDeviceId": ID_HIGH,
            "initiatorEphemeralKey": "BOk3Q2xvd3IHN0YWJsZS1lcGhlbWVyYWwta2V5LWluaXRpYXRvcg==",
            "responderEphemeralKey": "BOk3Q2xvd3IHN0YWJsZS1lcGhlbWVyYWwta2V5LXJlc3BvbmRlcg==",
            "exporter": exporter,
            "bytes": b64::std_encode(&transcript),
        },
        "sealed": {
            "sigKey": b64::std_encode(&sig_key),
            "rdvIdUrl": rdv_today,
            "side": 0,
            "sidUrl": sid,
            "nonce": b64::std_encode(&nonce),
            "plaintext": plaintext,
            "bodyUrl": body,
        },
        "nodeAuth": {
            "nonce": b64::std_encode(&auth_nonce),
            "nodeUrl": b64::url_encode(&node),
            "message": b64::std_encode(&derive::auth_message(&auth_nonce, &node)),
            "nodeIdUrl": derive::node_id(&node),
        },
        "turnRest": {"secret": "test-secret", "expiry": 1_761_407_200u64, "sidUrl": sid, "side": 0, "username": username, "credential": credential},
    })
}

#[cfg(test)]
mod tests {
    #[test]
    fn committed_file_matches() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../protocol/test-vectors/connect-v1.json");
        let committed: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(path).expect("connect-v1.json")).expect("JSON");
        assert_eq!(committed, super::generate(), "regenerate with: cargo run -p bridgey-connect-proto --example vectors");
    }
}
