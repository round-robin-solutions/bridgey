package dev.bridgey.android

import java.io.File
import java.util.Base64
import javax.crypto.Mac
import javax.crypto.spec.SecretKeySpec
import org.json.JSONObject
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * A session recorded between two Bridgey session clients (rust/client, the core of the Windows app), checked frame
 * by frame with this app's own decoder, pairing checks, envelope tags, AES-GCM and feature decoding: what the
 * phone would do with the same bytes. Generated by rust/client/src/vectors.rs.
 */
class SessionClientVectorTest {
    private val vector = JSONObject(
        File(System.getProperty("bridgey.repoRoot"), "protocol/test-vectors/session-client-v1.json").readText(Charsets.UTF_8),
    )
    private val frames: List<Pair<String, Message>> = (0 until vector.getJSONArray("frames").length()).map { i ->
        val frame = vector.getJSONArray("frames").getJSONObject(i)
        frame.getString("from") to decodeProtocolMessage(frame.getString("line"))
    }
    private fun first(kind: String): Message = frames.first { it.second.kind == kind }.second
    private val key: ByteArray = Base64.getDecoder().decode(vector.getString("sessionKey"))

    @Test
    fun theFirstPairingCommitsRevealsAndShowsTheSameCode() {
        val offer = first("pairing.offer")
        val answer = first("pairing.answer")
        val reveal = first("pairing.reveal")
        assertEquals(2L, offer.protocolVersion)
        assertEquals(2L, answer.protocolVersion)
        assertEquals(null, offer.publicKey)
        assertTrue(SessionSecurity.commitmentMatches(offer.commitment!!, offer.sessionId, reveal.publicKey!!))

        val prk = Base64.getDecoder().decode(vector.getString("prk"))
        assertEquals(vector.getString("code"), SessionSecurity.sasCode(prk, reveal.publicKey, answer.publicKey!!))
        val expand = Mac.getInstance("HmacSHA256").apply { init(SecretKeySpec(prk, "HmacSHA256")) }
        assertArrayEquals(key, expand.doFinal("bridgey-pairing-v1".toByteArray() + byteArrayOf(1)))
    }

    @Test
    fun bothConfirmationsVerifyAsThePhoneChecksThem() {
        val offer = first("pairing.offer")
        val answer = first("pairing.answer")
        val reveal = first("pairing.reveal")
        val transcript = listOf(
            "bridgey-auth-v1", offer.sessionId, offer.deviceId!!, answer.deviceId!!, reveal.publicKey!!, answer.publicKey!!,
        ).joinToString("\u0000").toByteArray()
        val confirms = frames.map { it.second }.filter { it.kind == "pairing.confirm" }
        assertEquals(2, confirms.size)
        for (confirm in confirms) {
            assertTrue(Crypto.verifyConfirmationProof(key, offer.sessionId, confirm.deviceId!!, confirm.identityKey!!, confirm.proof!!))
            assertTrue(Crypto.verifySignature(confirm.identityKey, transcript, confirm.signature!!))
        }
    }

    @Test
    fun everyFrameAfterPairingIsTaggedAndOpens() {
        val initiator = first("pairing.offer").deviceId!!
        val responder = first("pairing.answer").deviceId!!
        val envelope = SessionSecurity.envelopeKey(key)
        var features = 0
        var clipboard: Message? = null
        for ((from, message) in frames.filter { !it.second.kind.startsWith("pairing.") }) {
            val sender = if (from == "initiator") initiator else responder
            assertTrue(message.kind, SessionSecurity.tagMatches(envelope, sender, message))
            when (message.kind) {
                "features.update" -> {
                    val decoded = decodeFeatureState(Crypto.decrypt(key, message.nonce!!, message.ciphertext!!)!!)
                    assertTrue(decoded.toString(), decoded is FeatureStateDecoding.State)
                    assertEquals(true, (decoded as FeatureStateDecoding.State).features[BridgeyFeature.CLIPBOARD])
                    features++
                }
                "clipboard.update" -> {
                    val text = Crypto.decrypt(key, message.nonce!!, message.ciphertext!!)!!.toString(Charsets.UTF_8)
                    assertEquals(vector.getString("clipboardText"), text)
                    clipboard = message
                }
            }
        }
        assertEquals(2, features)
        assertNotNull(clipboard)
        assertEquals(clipboard!!.messageId, first("clipboard.ack").messageId)
    }
}
