package dev.bridgey.android

import java.io.File
import java.security.MessageDigest
import java.util.Base64
import org.json.JSONObject
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * A resume recorded between two Bridgey session clients (rust/client, the core of the Windows app): the reconnect
 * after a drop, where the same file is offered again resumable, the receiver sends files.resume.wait while it re-reads
 * its partial, answers files.resume, the sender agrees with files.resume.ack and only the rest travels. Every frame is
 * opened here with this app's own decoder, envelope tags, fast frame code and FileResume.kt: what the phone would do
 * with the same bytes on either end. Generated by rust/client/src/vectors.rs.
 */
class SessionClientResumeVectorTest {
    private val vector = JSONObject(
        File(System.getProperty("bridgey.repoRoot") ?: "../..", "protocol/test-vectors/session-client-resume-v1.json").readText(Charsets.UTF_8),
    )
    private val key: ByteArray = Base64.getDecoder().decode(vector.getString("sessionKey"))
    private val frames = (0 until vector.getJSONArray("frames").length()).map { vector.getJSONArray("frames").getJSONObject(it) }
    private val file = vector.getJSONObject("file")
    private val size = file.getInt("size")
    private val data = ByteArray(size) { (it * 31 % 251).toByte() }
    private val resumeAt = vector.getLong("resumeAt")

    /** Each side's device ID, from its offer or answer. */
    private val ids: Map<String, String> = frames.filter { it.has("line") }.mapNotNull { frame ->
        val message = decodeProtocolMessage(frame.getString("line"))
        if (message.kind == "pairing.offer" || message.kind == "pairing.answer") frame.getString("from") to message.deviceId!! else null
    }.toMap()

    private fun sha(bytes: ByteArray, length: Int = bytes.size) = MessageDigest.getInstance("SHA-256").apply { update(bytes, 0, length) }.digest()

    @Test
    fun everyJsonFrameIsTaggedByItsSenderAndBothShowTheKey() {
        assertEquals("byte i is (i * 31) mod 251", file.getString("pattern"))
        assertEquals(file.getString("sha256"), Base64.getEncoder().encodeToString(sha(data)))
        val envelope = SessionSecurity.envelopeKey(key)
        var maps = 0
        for (frame in frames.filter { it.has("line") }) {
            val message = decodeProtocolMessage(frame.getString("line"))
            if (message.kind.startsWith("pairing.")) continue
            assertTrue(message.kind, SessionSecurity.tagMatches(envelope, ids.getValue(frame.getString("from")), message))
            if (message.kind == "features.update") {
                val state = decodeFeatureState(Crypto.decrypt(key, message.nonce!!, message.ciphertext!!)!!) as FeatureStateDecoding.State
                if (state.drafts[FILES_RESUME_FEATURE_KEY] == true) maps++
            }
        }
        assertEquals("both ends show files_resume_draft1", 2, maps)
    }

    /** What the phone checks as the receiver and as the sender of this file, frame by frame, in order. */
    @Test
    fun theResumeDecodesWithThisAppsOwnCodeAndOnlyTheRestTravels() {
        val frameKey = SessionSecurity.fastFrameKey(key)
        var transfer: String? = null
        val order = mutableListOf<String>()
        val tail = java.io.ByteArrayOutputStream()
        var nextSequence = 0L
        for (frame in frames) {
            val from = frame.getString("from")
            if (frame.has("binaryBase64")) {
                val bytes = Base64.getDecoder().decode(frame.getString("binaryBase64"))
                val payload = openFastFrameBody(bytes[1].toInt(), bytes.copyOfRange(FastFrame.HEADER_BYTES, bytes.size), frameKey, ids.getValue(from))
                assertEquals(FastFrame.CHUNK_KIND, payload.kind)
                assertEquals(transfer, payload.id)
                assertEquals("sequences from 0 after the offset", nextSequence++, payload.sequence)
                tail.write(payload.plaintext)
                order += "binary"
                continue
            }
            val message = decodeProtocolMessage(frame.getString("line"))
            if (message.kind.startsWith("pairing.")) continue
            order += message.kind
            val plain = message.ciphertext?.let { Crypto.decrypt(key, message.nonce!!, it)!! }
            when (message.kind) {
                "files.offer" -> {
                    val offer = JSONObject(String(plain!!, Charsets.UTF_8))
                    assertTrue("offered resumable", offer.optBoolean("resumable"))
                    assertEquals(size.toLong(), offer.getLong("size"))
                    assertTrue(FileResume.resumable(offer.getLong("size")))
                    assertEquals(message.transferId, offer.getString("transferId"))
                    transfer = message.transferId
                }
                "files.resume.wait" -> {
                    assertEquals("responder", from)
                    assertEquals(transfer, message.transferId)
                    assertNull("outer only", message.ciphertext)
                }
                "files.resume" -> {
                    // As the sender: the receiver's offset and prefix, checked against the block hashes of the file.
                    val (offset, prefix) = FileResume.parseResume(plain!!, transfer!!, size.toLong())!!
                    assertEquals(resumeAt, offset)
                    assertArrayEquals(sha(data, offset.toInt()), prefix)
                    val (sha256, length, blocks) = RunningHash.of(data.inputStream())
                    assertEquals(resumeAt to null, FileResume.senderAnswer(plain, transfer!!, length, sha256, blocks))
                }
                "files.resume.ack" -> {
                    // As the receiver: the proposed offset, agreed.
                    assertEquals(resumeAt, FileResume.parseAck(plain!!, transfer!!, resumeAt))
                    assertFalse(JSONObject(String(plain, Charsets.UTF_8)).has("reason"))
                }
                "files.complete" -> assertEquals(file.getString("sha256"), JSONObject(String(plain!!, Charsets.UTF_8)).getString("sha256"))
            }
        }
        assertNotNull(transfer)
        fun at(kind: String) = order.indexOf(kind).also { assertTrue("$kind recorded", it >= 0) }
        assertTrue(at("files.offer") < at("files.resume.wait"))
        assertTrue(at("files.resume.wait") < at("files.resume"))
        assertTrue(at("files.resume") < at("files.resume.ack"))
        assertTrue(at("files.resume.ack") < at("binary"))
        assertTrue(at("binary") < at("files.complete.ack"))
        assertFalse("files.resume instead of files.accept", "files.accept" in order)
        assertArrayEquals("only the bytes after the offset", data.copyOfRange(resumeAt.toInt(), size), tail.toByteArray())
        // The receiver continues its running hash from the verified prefix to the whole file's SHA-256.
        val (digest, prefix) = RunningHash.prefixOf(data.inputStream(), resumeAt)
        val running = RunningHash.resumed(digest, resumeAt, prefix)
        running.update(tail.toByteArray())
        assertEquals(file.getString("sha256"), Base64.getEncoder().encodeToString(running.finish()))
    }
}
