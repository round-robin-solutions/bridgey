package dev.bridgey.android

import dev.bridgey.android.routing.PresenceState
import dev.bridgey.android.routing.decodeDevicePresence
import java.io.File
import java.util.Base64
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * A session recorded between two Bridgey session clients (rust/client, the core of the Windows app) after pairing:
 * the responder sends what a phone sends (notifications, codes messages) and the Windows side answers. Every message
 * the Windows side sent is read here with the phone's own checks (PairingCoordinator.receiveNotificationAction,
 * receiveCodesMessage, decodeDevicePresence): what this phone would do with the same bytes.
 * Generated by rust/client/src/vectors.rs.
 */
class SessionClientNotificationsVectorTest {
    private val vector = JSONObject(
        File(System.getProperty("bridgey.repoRoot"), "protocol/test-vectors/session-client-notifications-v1.json").readText(Charsets.UTF_8),
    )
    private val key: ByteArray = Base64.getDecoder().decode(vector.getString("sessionKey"))
    private val frames: List<Pair<String, Message>> = (0 until vector.getJSONArray("frames").length()).map { i ->
        val frame = vector.getJSONArray("frames").getJSONObject(i)
        frame.getString("from") to decodeProtocolMessage(frame.getString("line"))
    }
    private val ids = frames.filter { it.second.kind == "pairing.offer" || it.second.kind == "pairing.answer" }
        .associate { it.first to it.second.deviceId!! }

    private fun fromWindows(kind: String): List<Message> = frames.filter { it.first == "initiator" && it.second.kind == kind }.map { it.second }
    private fun open(message: Message): ByteArray = Crypto.decrypt(key, message.nonce!!, message.ciphertext!!)!!

    @Test
    fun everyFrameIsTaggedByItsSender() {
        val envelope = SessionSecurity.envelopeKey(key)
        for ((from, message) in frames.filter { !it.second.kind.startsWith("pairing.") }) {
            assertTrue(message.kind, SessionSecurity.tagMatches(envelope, ids.getValue(from), message))
        }
    }

    @Test
    fun actionsRepliesAndDismissesPassThePhonesChecks() {
        val action = JSONObject(open(fromWindows("notifications.action").single()).toString(Charsets.UTF_8))
        val notificationId = action.optString("notificationId")
        val actionToken = action.optString("actionToken")
        val replyText = action.optString("replyText").takeIf { action.has("replyText") }
        assertTrue(notificationId.isNotBlank() && notificationId.length <= 512)
        assertTrue(actionToken.matches(Regex("[0-9a-f]{64}")))
        assertEquals(vector.getString("replyToken"), actionToken)
        assertEquals(vector.getString("replyText"), replyText)
        assertTrue((replyText?.length ?: 0) <= 4_096)
        val dismiss = JSONObject(open(fromWindows("notifications.dismiss").single()).toString(Charsets.UTF_8))
        assertTrue(dismiss.getString("notificationId").isNotBlank())
    }

    @Test
    fun codesMessagesPassThePhonesChecks() {
        val link = open(fromWindows("codes.link_request").single())
        assertTrue(link.size <= 1024)
        assertEquals(1, JSONObject(link.toString(Charsets.UTF_8)).optInt("version"))
        val result = open(fromWindows("codes.advertise_result").single())
        assertTrue(result.size <= 1024)
        val payload = JSONObject(result.toString(Charsets.UTF_8))
        assertEquals(1, payload.optInt("version"))
        assertEquals(vector.getString("serviceUuid"), payload.optString("serviceUuid"))
        assertEquals(false, payload.opt("ok") == true)
        assertEquals("unsupported", payload.optString("reason"))
    }

    @Test
    fun presenceDecodesAsThePhoneReadsIt() {
        val samples = fromWindows("presence.state").map { decodeDevicePresence(open(it)) }
        assertTrue(samples.isNotEmpty())
        samples.forEach { assertNotNull("the phone accepts every presence sample", it) }
        val sequences = samples.map { it!!.sequence }
        assertEquals("sequences rise within the session", sequences.sorted().distinct(), sequences)
        assertTrue("the PC reported itself locked", samples.any { it!!.state == PresenceState.LOCKED && it.idleSeconds == null })
    }
}
