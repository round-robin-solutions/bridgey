package dev.bridgey.android

import java.io.File
import java.util.Base64
import java.util.UUID
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * A session recorded between two Bridgey session clients (rust/client, the core of the Windows app) after pairing:
 * the responder sends a phone's link and media requests; the Windows side answers, sends media.state and a link. What
 * the Windows side sent is read with the phone's own code (QuickRequestSequence, validatedWebLink, MacMediaState.parse).
 * Generated by rust/client/src/vectors.rs.
 */
class SessionClientQuickVectorTest {
    private val vector = JSONObject(
        File(System.getProperty("bridgey.repoRoot"), "protocol/test-vectors/session-client-quick-v1.json").readText(Charsets.UTF_8),
    )
    private val key: ByteArray = Base64.getDecoder().decode(vector.getString("sessionKey"))
    private val frames: List<Pair<String, Message>> = (0 until vector.getJSONArray("frames").length()).map { i ->
        val frame = vector.getJSONArray("frames").getJSONObject(i)
        frame.getString("from") to decodeProtocolMessage(frame.getString("line"))
    }
    private val ids = frames.filter { it.second.kind == "pairing.offer" || it.second.kind == "pairing.answer" }.associate { it.first to it.second.deviceId!! }

    private fun fromWindows(kind: String) = frames.filter { it.first == "initiator" && it.second.kind == kind }.map {
        JSONObject(Crypto.decrypt(key, it.second.nonce!!, it.second.ciphertext!!)!!.toString(Charsets.UTF_8))
    }

    @Test
    fun everyFrameIsTaggedByItsSender() {
        val envelope = SessionSecurity.envelopeKey(key)
        for ((from, message) in frames.filter { !it.second.kind.startsWith("pairing.") }) {
            assertTrue(message.kind, SessionSecurity.tagMatches(envelope, ids.getValue(from), message))
        }
    }

    @Test
    fun mediaStateParsesAsThePhoneReadsIt() {
        val states = fromWindows("media.state").map { MacMediaState.parse(it) }
        states.forEach { assertNotNull("the phone accepts every media state the PC sends", it) }
        assertEquals("nothing playing yet", "Off", states.first()!!.player)
        val state = states.last()
        assertEquals("Spotify", state!!.player)
        assertTrue(state.playing)
        assertTrue(state.allows("seek"))
        assertTrue("no volume through the system's media controls", !state.allows("volume"))
    }

    @Test
    fun theLinkTheWindowsSideSendsPassesThePhonesChecks() {
        val request = fromWindows("quick.request").single()
        assertEquals(1, request.opt("version"))
        UUID.fromString(request.getString("requestId"))
        assertEquals("links", request.getString("feature"))
        assertEquals("offer", request.getString("action"))
        assertEquals(vector.getString("linkToPhone"), validatedWebLink(request.getString("value")))
        assertTrue(QuickRequestSequence().accept("links", request.getLong("sequence")))
    }

    @Test
    fun resultsAnswerThePhonesRequests() {
        val results = fromWindows("quick.result")
        val link = results.single { it.getString("feature") == "links" }
        assertEquals(true, link.opt("accepted"))
        assertEquals(true, link.opt("opened"))
        assertEquals(true, results.single { it.getString("feature") == "media" }.opt("accepted"))
    }
}
