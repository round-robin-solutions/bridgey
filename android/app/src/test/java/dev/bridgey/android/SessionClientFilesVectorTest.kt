package dev.bridgey.android

import java.io.File
import java.security.MessageDigest
import java.util.Base64
import java.util.UUID
import org.json.JSONObject
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * A session recorded between two Bridgey session clients (rust/client, the core of the Windows app) after pairing:
 * battery both ways, find device, one file in binary frames (files_fast_draft1) and one in JSON chunks. Every frame is
 * opened here with this app's own decoder, envelope tags, fast frame code and AES-GCM, and both files are reassembled:
 * what the phone would do with the same bytes. Generated by rust/client/src/vectors.rs.
 */
class SessionClientFilesVectorTest {
    private val vector = JSONObject(
        File(System.getProperty("bridgey.repoRoot"), "protocol/test-vectors/session-client-files-v1.json").readText(Charsets.UTF_8),
    )
    private val key: ByteArray = Base64.getDecoder().decode(vector.getString("sessionKey"))
    private val frames = (0 until vector.getJSONArray("frames").length()).map { vector.getJSONArray("frames").getJSONObject(it) }

    /** Each side's device ID, from its offer or answer. */
    private val ids: Map<String, String> = frames.filter { it.has("line") }.mapNotNull { frame ->
        val message = decodeProtocolMessage(frame.getString("line"))
        if (message.kind == "pairing.offer" || message.kind == "pairing.answer") frame.getString("from") to message.deviceId!! else null
    }.toMap()

    @Test
    fun everyJsonFrameIsTaggedByItsSenderAndOpens() {
        val envelope = SessionSecurity.envelopeKey(key)
        val kinds = mutableSetOf<String>()
        for (frame in frames.filter { it.has("line") }) {
            val message = decodeProtocolMessage(frame.getString("line"))
            if (message.kind.startsWith("pairing.")) continue
            assertTrue(message.kind, SessionSecurity.tagMatches(envelope, ids.getValue(frame.getString("from")), message))
            kinds += message.kind
            if (message.ciphertext != null) assertTrue(message.kind, Crypto.decrypt(key, message.nonce!!, message.ciphertext!!) != null)
        }
        for (kind in listOf("battery.update", "find.start", "find.started", "find.stopped", "files.offer", "files.accept", "files.chunk",
            "files.chunk.ack", "files.complete", "files.complete.ack")) {
            assertTrue("$kind recorded", kind in kinds)
        }
    }

    @Test
    fun batteryAndFindPayloadsAreWhatThePhoneTakes() {
        for (frame in frames.filter { it.has("line") }) {
            val message = decodeProtocolMessage(frame.getString("line"))
            val plain = message.ciphertext?.let { Crypto.decrypt(key, message.nonce!!, it)!!.toString(Charsets.UTF_8) } ?: continue
            when (message.kind) {
                "battery.update" -> {
                    val payload = JSONObject(plain)
                    val expected = vector.getJSONObject("battery").getJSONObject(frame.getString("from"))
                    assertEquals(expected.getInt("level"), payload.getInt("level"))
                    assertEquals(expected.getBoolean("isCharging"), payload.getBoolean("isCharging"))
                }
                // receiveFindAcknowledgement fails the session for any other alert ID.
                "find.start", "find.started", "find.stopped" -> assertEquals("active", JSONObject(plain).getString("alertId"))
            }
        }
    }

    @Test
    fun bothFilesReassembleFromBinaryFramesAndJsonChunks() {
        val frameKey = SessionSecurity.fastFrameKey(key)
        val offers = mutableMapOf<String, JSONObject>()
        val completes = mutableMapOf<String, String>()
        val chunks = mutableMapOf<String, MutableList<Triple<Long, ByteArray, Boolean>>>()
        for (frame in frames) {
            val from = frame.getString("from")
            if (frame.has("binaryBase64")) {
                val bytes = Base64.getDecoder().decode(frame.getString("binaryBase64"))
                assertEquals(FastFrame.MARKER, bytes[0])
                val length = ((bytes[2].toInt() and 0xff) shl 24) or ((bytes[3].toInt() and 0xff) shl 16) or
                    ((bytes[4].toInt() and 0xff) shl 8) or (bytes[5].toInt() and 0xff)
                assertEquals(bytes.size - FastFrame.HEADER_BYTES, length)
                val payload = openFastFrameBody(bytes[1].toInt(), bytes.copyOfRange(FastFrame.HEADER_BYTES, bytes.size), frameKey, ids.getValue(from))
                assertEquals(FastFrame.CHUNK_KIND, payload.kind)
                chunks.getOrPut(payload.id) { mutableListOf() } += Triple(payload.sequence, payload.plaintext, true)
                continue
            }
            val message = decodeProtocolMessage(frame.getString("line"))
            val plain = message.ciphertext?.let { Crypto.decrypt(key, message.nonce!!, it)!! }
            when (message.kind) {
                "files.offer" -> {
                    val payload = JSONObject(plain!!.toString(Charsets.UTF_8))
                    // The checks receiveFileOffer makes before it accepts.
                    val transferId = payload.getString("transferId")
                    UUID.fromString(transferId)
                    assertEquals(message.transferId, transferId)
                    assertTrue(payload.getString("name").isNotBlank())
                    assertTrue(payload.getLong("size") >= 0)
                    assertEquals(32, Base64.getDecoder().decode(payload.getString("sha256")).size)
                    offers[transferId] = payload
                }
                "files.chunk" -> {
                    assertTrue("a JSON chunk carries its own messageId", message.messageId != null)
                    chunks.getOrPut(message.transferId!!) { mutableListOf() } += Triple(message.sequence!!, plain!!, false)
                }
                "files.complete" -> {
                    val payload = JSONObject(plain!!.toString(Charsets.UTF_8))
                    completes[payload.getString("transferId")] = payload.getString("sha256")
                }
            }
        }
        val files = vector.getJSONArray("files")
        assertEquals(2, files.length())
        for (i in 0 until files.length()) {
            val file = files.getJSONObject(i)
            val (id, offer) = offers.entries.single { it.value.getString("name") == file.getString("name") }
            val parts = chunks.getValue(id).sortedBy { it.first }
            assertTrue(parts.all { it.third == file.getBoolean("binary") })
            assertEquals((0L until parts.size).toList(), parts.map { it.first })
            val data = parts.fold(ByteArray(0)) { acc, part -> acc + part.second }
            assertArrayEquals(file.getString("text").toByteArray(Charsets.UTF_8), data)
            assertEquals(offer.getLong("size"), data.size.toLong())
            val digest = Base64.getEncoder().encodeToString(MessageDigest.getInstance("SHA-256").digest(data))
            assertEquals(offer.getString("sha256"), digest)
            assertEquals(digest, completes.getValue(id))
        }
    }
}
