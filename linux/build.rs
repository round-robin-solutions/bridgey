//! Edition constants from rr-edition.properties and the release key from the Mac's Info.plist, so Linux reads the
//! same single files as Gradle, macos/build-app.sh, Windows and scripts/rr. BRIDGEY_VERSION_NAME and
//! BRIDGEY_BUILD_NUMBER come from a release (scripts/rr/build-linux.sh); a local build is `<next>-dev`, build 1.

use std::collections::HashMap;
use std::path::Path;

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let props_path = root.join("rr-edition.properties");
    let plist_path = root.join("macos/Resources/Info.plist");
    println!("cargo:rerun-if-changed={}", props_path.display());
    println!("cargo:rerun-if-changed={}", plist_path.display());
    println!("cargo:rerun-if-env-changed=BRIDGEY_VERSION_NAME");
    println!("cargo:rerun-if-env-changed=BRIDGEY_BUILD_NUMBER");

    let text = std::fs::read_to_string(&props_path).expect("rr-edition.properties");
    let props: HashMap<String, String> = text
        .lines()
        .filter(|l| !l.trim_start().starts_with('#'))
        .filter_map(|l| l.split_once('='))
        .map(|(k, v)| (k.trim().to_string(), v.trim().to_string()))
        .collect();
    let get = |k: &str| props.get(k).cloned().unwrap_or_else(|| panic!("{k} missing from rr-edition.properties"));

    let plist = std::fs::read_to_string(&plist_path).expect("Info.plist");
    let key = plist
        .split("<key>SUPublicEDKey</key>")
        .nth(1)
        .and_then(|rest| rest.split("<string>").nth(1))
        .and_then(|rest| rest.split("</string>").next())
        .expect("SUPublicEDKey in Info.plist")
        .trim()
        .to_string();

    let version = std::env::var("BRIDGEY_VERSION_NAME").ok().filter(|v| !v.is_empty()).unwrap_or_else(|| format!("{}-dev", get("EDITION_NEXT_VERSION")));
    let build: u64 = std::env::var("BRIDGEY_BUILD_NUMBER").ok().and_then(|b| b.parse().ok()).unwrap_or(1);

    let out = format!(
        "// Generated by build.rs from rr-edition.properties and macos/Resources/Info.plist.\n\
         pub const APP_ID: &str = {:?};\n\
         pub const DISPLAY_NAME: &str = {:?};\n\
         pub const SHORT_NAME: &str = {:?};\n\
         pub const ASSET_PREFIX: &str = {:?};\n\
         pub const UPSTREAM_BASE: &str = {:?};\n\
         pub const REPOSITORY: &str = {:?};\n\
         pub const CONNECT_CONTROL_URL: &str = {:?};\n\
         pub const UPDATE_FEED_BASE: &str = {:?};\n\
         pub const UPDATE_ASSET_PREFIX: &str = {:?};\n\
         pub const UPDATE_PUBLIC_KEY: &str = {:?};\n\
         pub const VERSION_NAME: &str = {:?};\n\
         pub const BUILD_NUMBER: u64 = {};\n",
        get("EDITION_APP_ID"),
        get("EDITION_DISPLAY_NAME"),
        get("EDITION_SHORT_NAME"),
        get("EDITION_ASSET_PREFIX"),
        get("EDITION_UPSTREAM_BASE"),
        get("GITHUB_REPO"),
        get("CONNECT_CONTROL_URL"),
        get("UPDATE_FEED_BASE_URL"),
        get("UPDATE_ASSET_URL_PREFIX"),
        key,
        version,
        build
    );
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("edition.rs");
    std::fs::write(dest, out).unwrap();
}
